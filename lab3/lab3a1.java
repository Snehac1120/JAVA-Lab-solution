public class lab3a1 {
    public static void main(String[] args) {
        int a=10;
        int b=20;
        int c=30;

        System.out.println("Operator Precedence");
        System.out.println("a+b*c="+(a+b*c));

        int d=100;
        int e=10;

        System.out.println("d/e*d="+(d/e*d));

        int f=5;
        int g=4;
        int h=3;

        System.out.println("f*g/g%h="+(f*g/g%h));

        int i=100;
        int j=200;
        int k=10;
        int l=3;
        int m=10;

        System.out.println("i+j/k-l*m="+(i+j/k-l*m));
    }
}
